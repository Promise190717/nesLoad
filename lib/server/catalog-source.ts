/*
 * 前台目录数据的「从哪儿取」开关（2026-10-19）。
 *
 * ---------------------------------------------------------------------------
 * 为什么是环境变量，不是「D1 报错了就自动换」
 *
 * 先做过一版：`lib/server/d1.ts` 把额度用尽 / 限流 / 5xx 收敛成 `D1UnavailableError`，
 * 数据层看到它就自动改吃上游。用户随后否掉了这个判断方式 —— 改成**一个环境变量说了算**。
 * 理由是自动切换有三个躲不掉的问题：
 *
 *   1. **两套 id 不是一回事**：D1 里游戏 id 是 UUID，上游是 slug。自动切换时同一款游戏
 *      可能「列表页给 UUID、详情页给 slug」，而评论 / 收藏 / 历史 / 存档全按 id 存 ——
 *      数据会静默对不上，等发现时已经写脏一批。
 *   2. **猜不准**：额度到底用没用完、什么时候恢复，代码只能从错误文本里猜。
 *      猜错的代价是「线上数据忽然变成另一套」，排查时无从下手。
 *   3. **不好复现**：自动切换只在额度耗尽那天发生，本地和 CI 都复现不出来。
 *      环境变量随时能两个方向各验一遍。
 *
 * ---------------------------------------------------------------------------
 * 取值
 *
 *   · `upstream`（**默认**）—— 首页 / 列表 / 详情 / 机种 / 开发商 / ROM 代理全走源站
 *     （retrogamesnexus.com，见 `upstream-catalog.ts`）；
 *   · `d1` —— 全部走数据库，即原来的行为。
 *
 * ⚠️ 只影响**前台读取**（`games.ts` / `consoles.ts` / `developers.ts` 里那几个 cached
 *    包装函数 + ROM 代理 + sitemap 的游戏清单）。后台、评论、收藏、存档、账号
 *    **一律照旧走 D1** —— 那些数据源站没有。
 *
 * ⚠️ 大小写不敏感；认不出的值（含空串、拼错）一律按默认 `upstream` 处理，**不报错**。
 *    部署时少写一个变量就整站起不来，比走默认值糟得多。
 */

export type CatalogSource = 'upstream' | 'd1';

/** 当前来源。每次调用都重新读 env（改了变量重启即生效，不需要额外缓存）。 */
export function catalogSource(): CatalogSource {
  return process.env.CATALOG_SOURCE?.trim().toLowerCase() === 'd1' ? 'd1' : 'upstream';
}

/** 前台目录数据是否走源站（默认 true）。数据层里当分支条件用。 */
export function usesUpstreamCatalog(): boolean {
  return catalogSource() === 'upstream';
}
