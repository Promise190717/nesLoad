/**
 * 云端存档的体积上限，**唯一来源**：服务端在 `/api/user/saves` 里挡，客户端在发送前预检。
 *
 * 为什么客户端也要知道：Cloudflare（Pages Functions）的**请求体硬限是 100MB**，
 * 超了在**边缘**就回 `413 Request Entity Too Large`，请求根本进不到函数里 —— 白传一趟，
 * 还只能给出一句含糊的失败。发送前量一下 `blob.size`，就能当场给出确定的提示。
 *
 * 20MB 对**电池存档**来说宽得离谱（NDS 的卡带存档 128KB~1MB，其余机种 8~128KB）。
 * 它是按**快照**定的尺码（快照时代 NES 13.8KB、SFC 421KB，但也得防恶意大包），
 * 换成电池存档之后它就成了一道纯保险，正常流程永远碰不到。
 *
 * ⚠️ 别把它调小到「刚好卡住电池存档」—— 它同时兜住 middleware 之外的 body 解析，
 * 真正该拦的是「大到不像存档」的包，不是正常存档。
 */
export const MAX_SAVE_BYTES = 20 * 1024 * 1024;
