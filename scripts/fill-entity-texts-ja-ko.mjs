const D1_URL = `https://api.cloudflare.com/client/v4/accounts/${CF_ACCOUNT_ID}/d1/database/${D1_DATABASE_ID}/query`;

/** 跑一条 SQL。D1 的 `/query` 单次只吃一条语句（但可以带参数）。 */
async function run(sql, params = []) {
  const res = await fetch(D1_URL, {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${CF_D1_API_TOKEN}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({ sql, params }),
  });
  const data = await res.json();
  if (!res.ok || !data.success || !data.result?.[0]?.success) {
    const detail = (data.errors ?? []).map((e) => e.message).filter(Boolean).join('; ');
    throw new Error(`${detail || `HTTP ${res.status}`}（语句：${sql.replace(/\s+/g, ' ').slice(0, 140)}）`);
  }
  return data.result[0].results ?? [];
}

/** 空串 / 纯空白当「没有」，存 NULL。 */
function text(value) {
  const s = value == null ? '' : String(value).trim();
  return s === '' ? null : s;
}

/**
 * 写一行。默认 `DO NOTHING`（只补缺），`--force` 才 `DO UPDATE`（覆盖）。
 * ⚠️ 表的键列不同（机种是 `console_type`、厂商是 `developer_id`），所以拼表名/列名 ——
 *    值是参数绑定，不会被注入。
 */
async function upsert(table, keyColumn, key, locale, row, now) {
  const conflict = FORCE
    ? `DO UPDATE SET
         name = excluded.name,
         summary = excluded.summary,
         description = excluded.description,
         updated_at = excluded.updated_at`
    : 'DO NOTHING';
  await run(
    `INSERT INTO ${table} (${keyColumn}, locale, name, summary, description, updated_at)
     VALUES (?, ?, ?, ?, ?, ?)
     ON CONFLICT(${keyColumn}, locale) ${conflict}`,
    [key, locale, text(row.name), text(row.summary), text(row.description), now]
  );
}

async function main() {
  const now = Date.now();
  console.log(DRY_RUN ? '== 干跑（不写库）==' : FORCE ? '== 真跑（--force 覆盖）==' : '== 真跑 ==');
  console.log(`目标语言：${TARGET_LOCALES.join(' / ')}${ONLY ? '（--only）' : ''}\n`);

  let written = 0;

  /* 机种 */
  const consoleTypes = Object.keys(CONSOLES);
  for (const type of consoleTypes) {
    for (const locale of TARGET_LOCALES) {
      const row = CONSOLES[type]?.[locale];
      if (!row) {
        console.log(`⚠️ 机种 ${type} 缺 ${locale} 文案，跳过`);
        continue;
      }
      if (DRY_RUN) {
        console.log(`· [dry-run] console_texts ${type} [${locale}] → ${row.name}`);
      } else {
        await upsert('console_texts', 'console_type', type, locale, row, now);
      }
      written += 1;
    }
  }
  console.log(`机种 ${consoleTypes.length} 台 × ${TARGET_LOCALES.length} 语言 = ${consoleTypes.length * TARGET_LOCALES.length} 行。\n`);

  /* 开发商 */
  for (const dev of DEVELOPERS) {
    for (const locale of TARGET_LOCALES) {
      const row = dev?.[locale];
      if (!row) {
        console.log(`⚠️ 开发商 ${dev?.id ?? '(无 id)'} 缺 ${locale} 文案，跳过`);
        continue;
      }
      if (DRY_RUN) {
        console.log(`· [dry-run] developer_texts ${dev.id.slice(0, 8)} [${locale}] → ${row.name}`);
      } else {
        await upsert('developer_texts', 'developer_id', dev.id, locale, row, now);
      }
      written += 1;
    }
  }
  console.log(`开发商 ${DEVELOPERS.length} 家 × ${TARGET_LOCALES.length} 语言 = ${DEVELOPERS.length * TARGET_LOCALES.length} 行。`);

  if (DRY_RUN) {
    console.log(`\n[dry-run] 共会写 ${written} 行；什么都没落库。去掉 --dry-run 再跑一次才写。`);
    return;
  }

  // 回读
  const c = await run(
    `SELECT locale, COUNT(*) AS n FROM console_texts WHERE locale IN (${TARGET_LOCALES.map(() => '?').join(',')}) GROUP BY locale ORDER BY locale`,
    TARGET_LOCALES
  );
  const d = await run(
    `SELECT locale, COUNT(*) AS n FROM developer_texts WHERE locale IN (${TARGET_LOCALES.map(() => '?').join(',')}) GROUP BY locale ORDER BY locale`,
    TARGET_LOCALES
  );
  console.log(
    `\n[done] 共写 ${written} 行（默认只补缺；加 --force 才是覆盖）。` +
      `\n       console_texts：${c.map((r) => `${r.locale}=${r.n}`).join(' · ')}` +
      `\n       developer_texts：${d.map((r) => `${r.locale}=${r.n}`).join(' · ')}`
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
