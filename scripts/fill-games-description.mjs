/*
 * 给 games 表里**还没有说明**的记录补上「说明」文案（2026-10-12 用户要求）。
 *
 * 用法：
 *   node --env-file=.env.local scripts/fill-games-description.mjs
 *   node --env-file=.env.local scripts/fill-games-description.mjs --dry-run   # 只看要改哪些，不写库
 *
 * 和 add-games-description.mjs 的分工：
 *   那个脚本负责**加列**（结构），这个负责**填内容**（数据）。
 *
 * ⚠️ 两条安全约定：
 *   ① 只会写 `description IS NULL / 全空白` 的行 —— 后台手填过的说明**不会被覆盖**，
 *      所以这个脚本可以反复执行，加新游戏之后再跑一次只补新的那几条。
 *   ② 全程只有 `UPDATE games SET description = ? WHERE id = ?`，
 *      没有 DELETE / DROP / 改别的列；改前改后各打一次总条数。
 *
 * 文案维护在下面 `DESCRIPTIONS` 里，**以 id 为键**（标题有重名的：
 * 「塞尔达传说：众神的三角力量」中英两版就是两条记录）。
 * 每条控制在 250 字以内；这段文字会直接显示在 `/games/<id>` 详情页正文，
 * 也会**截前 100 字**拼进 meta description（见 app/games/[id]/page.tsx）。
 */
const { CF_ACCOUNT_ID, CF_D1_API_TOKEN, D1_DATABASE_ID } = process.env;
const DRY_RUN = process.argv.includes('--dry-run');

if (!CF_ACCOUNT_ID || !CF_D1_API_TOKEN || !D1_DATABASE_ID) {
  console.error('缺少环境变量：需要 CF_ACCOUNT_ID / CF_D1_API_TOKEN / D1_DATABASE_ID');
  console.error('用法：node --env-file=.env.local scripts/fill-games-description.mjs');
  process.exit(1);
}

const url = `https://api.cloudflare.com/client/v4/accounts/${CF_ACCOUNT_ID}/d1/database/${D1_DATABASE_ID}/query`;

/** 跑一条 SQL（带绑定参数），返回 D1 那一整条 result（含 meta.changes）。 */
async function run(sql, params = []) {
  const res = await fetch(url, {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${CF_D1_API_TOKEN}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({ sql, params }),
  });
  const data = await res.json();
  if (!res.ok || !data.success || !data.result?.[0]?.success) {
    const detail = (data.errors ?? []).map((e) => e.message).filter(Boolean).join('; ');
    throw new Error(`${detail || `HTTP ${res.status}`}（语句：${sql.replace(/\s+/g, ' ')}）`);
  }
  return data.result[0];
}

