const countRows = async () => Number((await run('SELECT COUNT(*) AS n FROM games')).results[0]?.n ?? 0);

const before = await countRows();
console.log(`games 现有 ${before} 条记录，文案共 ${DESCRIPTIONS.length} 条。`);

/* 先把库里的 id / 现有说明捞出来，好判断「有哪些对不上」 */
const rows = (await run('SELECT id, title, description FROM games')).results;
const byId = new Map(rows.map((row) => [row.id, row]));

const missing = DESCRIPTIONS.filter((entry) => !byId.has(entry.id));
if (missing.length) {
  console.error(`⚠️ 下面这些 id 在库里找不到（文案没写库）：`);
  for (const entry of missing) console.error(`   ${entry.id}  ${entry.title}`);
}

let updated = 0;
let skipped = 0;

for (const entry of DESCRIPTIONS) {
  const row = byId.get(entry.id);
  if (!row) continue;

  if (row.description != null && String(row.description).trim() !== '') {
    skipped += 1;
    console.log(`· 跳过（已有说明）：${entry.title}`);
    continue;
  }

  if (entry.text.length > 250) {
    console.error(`⚠️ ${entry.title} 的说明有 ${entry.text.length} 字，超过 250 字上限 —— 没写库。`);
    continue;
  }

  if (DRY_RUN) {
    console.log(`· [dry-run] 会写入：${entry.title}（${entry.text.length} 字）`);
    updated += 1;
    continue;
  }

  try {
    const result = await run(
      "UPDATE games SET description = ? WHERE id = ? AND (description IS NULL OR TRIM(description) = '')",
      [entry.text, entry.id],
    );
    if (result.meta?.changes) {
      updated += 1;
      console.log(`✅ ${entry.title}（${entry.text.length} 字）`);
    } else {
      skipped += 1;
      console.log(`· 跳过（写入时条件已不成立）：${entry.title}`);
    }
  } catch (error) {
    console.error(`❌ ${entry.title} 写入失败：${error.message}`);
  }
}

const after = await countRows();
console.log('---');
console.log(`${DRY_RUN ? '[dry-run] 预计写入' : '写入'} ${updated} 条，跳过 ${skipped} 条。`);
console.log(`games 现在 ${after} 条记录。${after === before ? '✅ 一条没多、一条没少。' : '⚠️ 条数变了，请核对！'}`);
