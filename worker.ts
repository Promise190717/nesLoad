/*
 * OpenNext 的**自定义 Worker 入口**（`wrangler.jsonc` 的 `main` 指向这里），
 * 在 OpenNext 生成的 handler 外面包一层 **Cache API 边缘缓存**。
 *
 * 为什么需要它（2026-10-24）：
 *
 *   10-22 迁 Vercel 后全站页面都是 `force-dynamic`（撤销了页面级 ISR），而实际部署
 *   仍走 Cloudflare 免费版 Workers —— 每个请求都要现场跑一遍 React SSR，免费版
 *   10ms CPU（按中位数执行）根本装不下，线上 2/3 的请求 1102
 *   （Worker exceeded CPU time limit）。`enableCacheInterception` 只能拦截
 *   Next 自己缓存过的路由，对 `force-dynamic` 完全无效，所以缓存在这里、
 *   在 Next 外面做。
 *
 *   这**不是 ISR**：没有 R2 存 HTML、没有 DO/tag cache、没有再验证机制，
 *   就是边缘上一份按 TTL 过期的响应副本，TTL 到了自然淘汰；发版想立刻生效就在
 *   仪表盘（Caching → Purge Everything）刷一次，或者等 TTL 自然过期——
 *   刻意把 TTL 定得很短，等得起。
 *
 * 规则（刻意收得很窄，宁可少缓存也不缓存错）：
 *   · 只缓存 **匿名** `GET` —— 带 `nesload_user` / `nesload_admin` cookie 的请求
 *     直接放行（登录态虽然主要在客户端渲染，但详情页的评论框初值是服务端读
 *     cookie 出的，不能让登录用户吃别人的缓存副本）；
 *   · 只缓存 **200 / 404** 且内容是 HTML / XML / 纯文本的响应——`/api/*`、
 *     `/admin/*`、`/_next/*` 在路径上就放行，重定向（语言 307 / 301）和 5xx
 *     一律不缓存：语言跳转依赖 cookie，缓存了会把没设过语言的人跳去错误的语言；
 *   · 带 `RSC` 请求头的软导航请求放行——它们要的是 flight 数据不是 HTML，
 *     键是同一个 URL，缓存了会把 HTML 塞给客户端路由器；
 *   · 缓存键剥掉 `utm_*` / `fbclid` / `gclid` 这类追踪参数——同一页面不因
 *     分享链接上的参数多存一份、多渲染一次。
 *
 * TTL：200 存 10 分钟，404 存 2 分钟（挡扫描器对不存在地址的反复试探——
 * 每次试探都是一次会超限的渲染）。页面内容只有后台上传游戏时才变（数据层
 * 还有 7 天缓存），10 分钟的陈旧窗口对用户和爬虫都无感。
 *
 * ⚠️ **静态资产不走这里**：`assets` 绑定的文件（`/_next/static`、`/cores`、
 *    `/sprites`…）由 Cloudflare 直接服务、不进 Worker，免费额度也不计入请求——
 *    所以不用 wrangler 的 `"cache": { "enabled": true }`（那会把资产请求也变成
 *    计费请求），包这一层是计费更省、控制面更窄的等价物。
 *
 * ⚠️ 缓存条目**跨发版存活**：发版后最多 10 分钟内可能混着旧版 HTML。
 *    不可接受就在仪表盘 purge 一次；可接受（默认）就不用管。
 *
 * 参照 https://opennext.js.org/cloudflare/howtos/custom-worker 的官方写法：
 * `DOQueueHandler` / `DOShardedTagCache` 必须从这个入口再导出，否则
 * wrangler.jsonc 里那两个 DO 的迁移会因为「类不在入口 worker 上」而失败。
 */

// 本文件不参与 tsc typecheck（tsconfig exclude），`.open-next/worker.js` 由
// `pnpm cf:build` 生成，运行时由 wrangler/esbuild 打包解析。
// @ts-expect-error `.open-next/worker.js` is generated by `pnpm cf:build`
import { default as handler } from './.open-next/worker.js';

/** 登录态 cookie —— 改名处：lib/server/app-session.ts / lib/server/session.ts */
const SESSION_COOKIE_NAMES = ['nesload_user', 'nesload_admin'];

/** 200 的边缘缓存时长（秒）。 */
const TTL_OK = 600;
/** 404 的边缘缓存时长（秒）。 */
const TTL_NOT_FOUND = 120;

/** 只缓存这些内容类型（HTML 页面 + sitemap/robots/llms 这类站点文件）。 */
const CACHEABLE_CONTENT_TYPES = /^(text\/html|text\/plain|application\/xml|text\/xml)\b/i;

/** 缓存键里要剥掉的追踪参数。 */
const TRACKING_PARAM = /^(utm_|fbclid|gclid|msclkid)/i;

function isInternalPath(pathname: string): boolean {
  return (
    pathname.startsWith('/api/') ||
    pathname === '/api' ||
    pathname.startsWith('/admin') ||
    pathname.startsWith('/_next/')
  );
}

function hasSessionCookie(headers: Headers): boolean {
  const cookie = headers.get('cookie');
  if (!cookie) return false;
  return SESSION_COOKIE_NAMES.some((name) => cookie.includes(`${name}=`));
}

/** 剥掉追踪参数后的缓存键。不直接用原 request：键要和「分享链接上带了参数」的请求对得上。 */
function cacheKey(request: Request): Request {
  const url = new URL(request.url);
  for (const name of [...url.searchParams.keys()]) {
    if (TRACKING_PARAM.test(name)) url.searchParams.delete(name);
  }
  return new Request(url.toString(), { method: 'GET' });
}

const edgeCacheWrapper = {
  async fetch(
    request: Request,
    env: unknown,
    ctx: { waitUntil(promise: Promise<unknown>): void }
  ): Promise<Response> {
    // 只考虑匿名的 GET 页面请求；其余原样交给 OpenNext。
    if (request.method !== 'GET' || hasSessionCookie(request.headers)) {
      return handler.fetch(request, env, ctx);
    }
    const url = new URL(request.url);
    if (isInternalPath(url.pathname) || request.headers.has('rsc')) {
      return handler.fetch(request, env, ctx);
    }

    const cache = (caches as unknown as { default: Cache }).default;
    const key = cacheKey(request);
    const hit = await cache.match(key);
    if (hit) return hit;

    const response = await handler.fetch(request, env, ctx);

    const ttl = response.status === 200 ? TTL_OK : response.status === 404 ? TTL_NOT_FOUND : 0;
    const contentType = response.headers.get('content-type') ?? '';
    if (ttl > 0 && !response.headers.has('set-cookie') && CACHEABLE_CONTENT_TYPES.test(contentType)) {
      ctx.waitUntil(cache.put(key, response.clone(), { cacheTtl: ttl }));
    }
    return response;
  },
};

export default edgeCacheWrapper;

// @ts-expect-error `.open-next/worker.js` is generated by `pnpm cf:build`
export { DOQueueHandler, DOShardedTagCache } from './.open-next/worker.js';
